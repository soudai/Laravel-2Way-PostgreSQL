<?php

declare(strict_types=1);

namespace Hft\TwoWaySql\Codegen\Dao;

use Hft\TwoWaySql\Codegen\Definition\DaoDefinition;
use Hft\TwoWaySql\Codegen\Definition\MethodDefinition;
use Hft\TwoWaySql\Codegen\Definition\TypeNames;
use Hft\TwoWaySql\Exception\ErrorCode;
use Hft\TwoWaySql\Exception\SqlException;

final class DaoGenerator
{
    /** @param list<DaoDefinition> $definitions */
    public function generate(array $definitions, string $namespace): GeneratedBundle
    {
        if (! TypeNames::className($namespace)) {
            throw new SqlException(ErrorCode::Generation);
        }
        $files = [];
        $names = [];
        $bindings = [];
        $schemas = [];
        foreach ($definitions as $definition) {
            $parts = explode('\\', $definition->interface);
            $name = end($parts).'Impl';
            if (isset($names[strtolower($name)]) || isset($bindings[$definition->interface])) {
                throw new SqlException(ErrorCode::Generation);
            }
            $names[strtolower($name)] = true;
            $source = "<?php\n\ndeclare(strict_types=1);\n\nnamespace ".$namespace.";\n\n// Generated by TwoWaySql; schema ".$definition->schemaHash."\n";
            $source .= 'final readonly class '.$name.' implements \\'.$definition->interface."\n{\n";
            $source .= "    public function __construct(private \\Hft\\TwoWaySql\\Laravel\\Executor\\Executor \$executor) {}\n";
            foreach ($definition->methods as $method) {
                $source .= $this->method($method);
            }
            $source .= "}\n";
            PhpSource::validate($source);
            $files[$name.'.php'] = $source;
            $bindings[$definition->interface] = $namespace.'\\'.$name;
            $schemas[$definition->interface] = $definition->toArray();
        }

        return new GeneratedBundle($files, $bindings, $schemas);
    }

    private function method(MethodDefinition $method): string
    {
        $arguments = [];
        $parameters = [];
        $docs = [];
        foreach ($method->arguments as $argument) {
            $arguments[] = '#[\\SensitiveParameter] '.$argument->type.' $'.$argument->name;
            $parameters[] = var_export($argument->name, true).' => $'.$argument->name;
            if ($argument->doc !== null) {
                $docs[] = '     * @param '.$argument->doc.' $'.$argument->name;
            } elseif (ltrim($argument->type, '?') === 'array') {
                $docs[] = '     * @param '.(str_starts_with($argument->type, '?') ? '?' : '').'array<array-key,mixed> $'.$argument->name;
            }
        }
        $input = $method->parameterClass === null ? '['.implode(', ', $parameters).']' : '$'.$method->arguments[0]->name;
        $call = $method->mode;
        $prefix = '';
        if ($method->resultClass !== null) {
            $call .= 'As';
            $prefix = '\\'.$method->resultClass.'::class, ';
        }
        $expression = '$this->executor->'.$call.'('.$prefix.var_export($method->query->id, true).', '.$input.')';
        $body = '        return '.$expression.";\n";
        if ($method->mode === 'scalar' && $method->returnType !== 'mixed') {
            $native = ltrim($method->returnType, '?');
            $guard = (str_starts_with($method->returnType, '?') ? '$value !== null && ' : '').'! is_'.$native.'($value)';
            $body = '        $value = '.$expression.";\n        if (".$guard.") {\n            throw new \\Hft\\TwoWaySql\\Exception\\MappingException(sqlId: ".var_export($method->query->id, true).");\n        }\n\n        return \$value;\n";
        }

        $doc = $docs === [] ? '    /** @return '.$method->returnDoc.' */' : "    /**\n".implode("\n", $docs)."\n     * @return ".$method->returnDoc."\n     */";

        return "\n".$doc."\n    public function ".$method->name.'('.implode(', ', $arguments).'): '.$method->returnType."\n    {\n".$body."    }\n";
    }
}
